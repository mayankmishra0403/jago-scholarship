const all: Record<LanguageCode, Dict> = {
  en,
  hi,
  sat: tribal.sat!,
  kui: tribal.kui!,
  ora: tribal.ora!,
  mun: tribal.mun!,
  gon: tribal.gon!,
  sora: tribal.sora!,
}

export function t(lang: LanguageCode, key: string, vars?: Record<string, string | number>): string {
  const dict = all[lang] ?? en
  let s = dict[key] ?? en[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
  }
  return s
}

/** National languages cover the full UI; tribal languages fall back to Hindi→English. */
export const isUiLanguage = (lang: LanguageCode) => lang === 'en' || lang === 'hi'

export const coverageLabel = (lang: LanguageCode) =>
  isUiLanguage(lang) ? 'Full app' : 'Assistant + explainers'
